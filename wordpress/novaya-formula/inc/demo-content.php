function nf_has_posts( $type ) {
	return (bool) get_posts(
		array(
			'post_type'      => $type,
			'post_status'    => 'any',
			'posts_per_page' => 1,
			'fields'         => 'ids',
		)
	);
}

function nf_create_item( $type, $item, $order ) {
	$post_id = wp_insert_post(
		array(
			'post_type'   => $type,
			'post_status' => 'publish',
			'post_title'  => $item['title'],
			'post_name'   => $item['slug'],
			'menu_order'  => $order,
		)
	);
	if ( ! $post_id || is_wp_error( $post_id ) ) {
		return;
	}
	foreach ( $item['meta'] as $key => $value ) {
		update_post_meta( $post_id, '_nf_' . $key, $value );
	}
	if ( ! empty( $item['image'] ) ) {
		$attachment = nf_import_image( $item['image'][0], $item['image'][1], $post_id );
		if ( $attachment ) {
			set_post_thumbnail( $post_id, $attachment );
		}
	}
}

/** Копирует фото из папки темы в медиабиблиотеку. Одно и то же фото загружается один раз. */
function nf_import_image( $file, $alt, $parent = 0 ) {
	static $done = array();
	if ( isset( $done[ $file ] ) ) {
		return $done[ $file ];
	}

	$path = NF_DIR . '/assets/images/' . $file;
	if ( ! file_exists( $path ) ) {
		return 0;
	}

	$upload = wp_upload_bits( $file, null, file_get_contents( $path ) ); // phpcs:ignore WordPress.WP.AlternativeFunctions
	if ( ! empty( $upload['error'] ) ) {
		return 0;
	}

	$type          = wp_check_filetype( $upload['file'] );
	$attachment_id = wp_insert_attachment(
		array(
			'post_mime_type' => $type['type'],
			'post_title'     => pathinfo( $file, PATHINFO_FILENAME ),
			'post_status'    => 'inherit',
		),
		$upload['file'],
		$parent
	);
	if ( ! $attachment_id || is_wp_error( $attachment_id ) ) {
		return 0;
	}

	require_once ABSPATH . 'wp-admin/includes/image.php';
	wp_update_attachment_metadata( $attachment_id, wp_generate_attachment_metadata( $attachment_id, $upload['file'] ) );
	if ( $alt ) {
		update_post_meta( $attachment_id, '_wp_attachment_image_alt', $alt );
	}

	$done[ $file ] = $attachment_id;
	return $attachment_id;
}
